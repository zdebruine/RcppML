# Re-save package data with the smallest safe encoding. Run from the package root with RcppML installed.
library(Matrix); library(RcppML)
before <- file.size(list.files("data", full.names = TRUE)); names(before) <- list.files("data")
load("data/pbmc3k.rda"); tmp <- tempfile(fileext = ".spz"); writeBin(pbmc3k, tmp)
print(st_info(tmp)); A <- st_read(tmp); cat("pbmc3k:", dim(A), length(A@x), "\n")
var <- tryCatch(st_read_var(tmp), error = function(e) NULL); obs <- tryCatch(st_read_obs(tmp), error = function(e) NULL)
out <- tempfile(fileext = ".spz")
st_write(A, out, obs = if (!is.null(obs) && nrow(obs)) obs, var = if (!is.null(var) && nrow(var)) var, include_transpose = FALSE)
B <- st_read(out); stopifnot(identical(dim(A), dim(B)), max(abs(A - B)) < 1e-6 * max(A@x))
old <- pbmc3k; pbmc3k <- readBin(out, "raw", file.size(out)); attributes(pbmc3k) <- attributes(old)
save(pbmc3k, file = "data/pbmc3k.rda", compress = "xz")
tools::resaveRdaFiles("data", compress = "xz")
after <- file.size(list.files("data", full.names = TRUE)); names(after) <- list.files("data")
print(round(cbind(before, after) / 1e6, 2)); cat("total MB:", round(sum(before) / 1e6, 2), "->", round(sum(after) / 1e6, 2), "\n")
